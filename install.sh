#!/usr/bin/env bash
# agent-usage one-shot installer. Run it either way:
#
#   curl -fsSL https://raw.githubusercontent.com/mfucek/agent-usage/main/install.sh | bash
#   ./install.sh                    # from a local clone
#
# Clones (or fast-forwards) the repo into ~/.local/share/agent-usage, runs
# `npm ci`, and drops an `agent-usage` launcher into ~/.local/bin. The live
# TUI updates that checkout itself from then on (see "Updates" in README.md).
#
# Re-running is safe: the clone becomes a fast-forward, the launcher is
# rewritten. Override the location with AGENT_USAGE_DIR=/some/path.

set -euo pipefail

REPO_URL="https://github.com/mfucek/agent-usage.git"
APP_DIR="${AGENT_USAGE_DIR:-$HOME/.local/share/agent-usage}"
SHIM_DIR="$HOME/.local/bin"
SHIM_PATH="$SHIM_DIR/agent-usage"

if [ -t 1 ]; then
  G=$'\033[32m'; Y=$'\033[33m'; R=$'\033[31m'; B=$'\033[1m'; D=$'\033[2m'; X=$'\033[0m'
else
  G=""; Y=""; R=""; B=""; D=""; X=""
fi
say()  { printf "%s>%s %s\n" "$G" "$X" "$*"; }
warn() { printf "%s!%s %s\n" "$Y" "$X" "$*"; }
err()  { printf "%sx%s %s\n" "$R" "$X" "$*" >&2; }

# ---- 1. git + node ----
if ! command -v git >/dev/null 2>&1; then
  err "git not found. Install Xcode Command Line Tools (xcode-select --install) or your package manager's git, then re-run."
  exit 1
fi
if ! command -v node >/dev/null 2>&1 || ! command -v npm >/dev/null 2>&1; then
  err "node/npm not found. Install Node.js 18 or newer (https://nodejs.org or \`brew install node\`), then re-run."
  exit 1
fi
NODE_MAJOR="$(node -p 'process.versions.node.split(".")[0]')"
if [ "$NODE_MAJOR" -lt 18 ]; then
  err "Node.js $(node --version) is too old — agent-usage needs 18 or newer."
  exit 1
fi

# ---- 2. clone or update ----
mkdir -p "$(dirname "$APP_DIR")"
if [ -d "$APP_DIR/.git" ]; then
  say "Updating existing install at $APP_DIR"
  git -C "$APP_DIR" fetch --quiet origin
  # Refuse to clobber local edits — let the user resolve.
  if ! git -C "$APP_DIR" diff --quiet || ! git -C "$APP_DIR" diff --cached --quiet; then
    warn "Local changes in $APP_DIR — skipping pull. Commit/stash them or rm -rf the dir and re-run."
  else
    git -C "$APP_DIR" merge --ff-only origin/HEAD >/dev/null 2>&1 || \
      git -C "$APP_DIR" merge --ff-only origin/main >/dev/null 2>&1 || \
      warn "Couldn't fast-forward. Working tree may be on a non-main branch — leaving it alone."
  fi
elif [ -e "$APP_DIR" ]; then
  err "$APP_DIR exists but isn't a git checkout. Move it aside and re-run."
  exit 1
else
  say "Cloning agent-usage → $APP_DIR"
  git clone --quiet "$REPO_URL" "$APP_DIR"
fi

# ---- 3. dependencies ----
say "Installing dependencies"
(cd "$APP_DIR" && npm ci --no-audit --no-fund --silent)

# ---- 4. launcher ----
# ~/.local/bin is the XDG-ish convention used by pipx, cargo install, etc.
# Avoids sudo. We warn if it's not on PATH.
mkdir -p "$SHIM_DIR"
cat > "$SHIM_PATH" <<SHIM
#!/bin/sh
# agent-usage launcher. Generated by install.sh — edit at your own risk.
APP="$APP_DIR"
[ -f "\$APP/bin/agent-usage.mjs" ] || { echo "agent-usage install not found at \$APP — re-run install.sh" >&2; exit 1; }
exec node "\$APP/bin/agent-usage.mjs" "\$@"
SHIM
chmod +x "$SHIM_PATH"
say "Installed launcher → $SHIM_PATH"

case ":$PATH:" in
  *":$SHIM_DIR:"*) ;;
  *)
    warn "$SHIM_DIR is not on your PATH."
    printf "  Add this line to your shell rc (~/.zshrc or ~/.bashrc) and reopen the terminal:\n"
    printf "    %sexport PATH=\"\$HOME/.local/bin:\$PATH\"%s\n" "$B" "$X"
    ;;
esac

cat <<EOF

${G}${B}agent-usage installed.${X}

${B}1. Check${X}
${D}   agent-usage --once     # one card for the account Claude Code is logged into${X}

${B}2. Run${X}
${D}   agent-usage            # live dashboard${X}

${B}3. Updates${X}
${D}   Automatic while the dashboard runs (turn off: agent-usage auto-update off).${X}
${D}   Manual: agent-usage update, or re-run this installer.${X}

EOF
